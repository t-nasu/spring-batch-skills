-- 結合テスト用。db/schema.sql（MySQL）と同じ列構成を H2 の記法で作る。
DROP TABLE IF EXISTS member_point;
DROP TABLE IF EXISTS point_expiration_history;

CREATE TABLE member_point (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT      NOT NULL,
    points     INT         NOT NULL,
    expires_on DATE        NOT NULL,
    status     VARCHAR(16) NOT NULL
);

CREATE TABLE point_expiration_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_point_id BIGINT NOT NULL,
    member_id       BIGINT NOT NULL,
    points          INT    NOT NULL,
    expired_on      DATE   NOT NULL,
    CONSTRAINT uk_point_expiration_history_point UNIQUE (member_point_id)
);
